@torch.compile
def MachPolar17(G: torch.Tensor, steps: int) -> torch.Tensor:
    assert G.ndim >= 2
    X = G.bfloat16()  # for speed
    if G.size(-2) > G.size(-1):
        X = X.mT  # this reduces FLOPs
    X = X / (X.norm(dim=(-2, -1), keepdim=True) * 1.01 + 1e-7)

    for i in range(0, steps):
        t = min(i, len(coeff_list) - 1)
        a0, a1, a2, b0, b1, b2, c0, c1, c2, c3, c4 = coeff_list[t]
        S1 = X @ X.mT
        S0 = torch.eye(S1.size(-1), dtype=S1.dtype, device=S1.device).expand_as(S1)
        S2 = S1 @ S1
        S3 = (a0 * S1 + S2) @ (b0 * S1 + S2)
        S4 = (a1 * S1 + a2 * S2 + S3) @ (b1 * S1 + b2 * S2 + S3)
        X = (c0 * S0 + c1 * S1 + c2 * S2 + c3 * S3 + c4 * S4) @ X

    if G.size(-2) > G.size(-1):
        X = X.mT
    return X